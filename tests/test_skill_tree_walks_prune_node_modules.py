"""The repository's own checks do not descend into the Skills' node_modules (Issue #1400).

Running the quartz-plugins' own tests creates
`.claude/skills/wikicommit-init/scripts/templates/quartz-plugins/*/node_modules/`
(gitignored, tens of thousands of files). Walks that filtered an `rglob()` after
the fact still descended into it, and each such test took 40-50 s on a machine
where those directories existed. These tests plant a `node_modules/` holding
`.md` files in a temporary tree and check that the walks neither return them nor
change what they do return. Speed itself is not asserted.
"""

import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tools"))

import check_skill_md_lines  # noqa: E402
import check_skill_tree_paths  # noqa: E402

PLUGIN = Path("scripts/templates/quartz-plugins/some-plugin")


def _write(path: Path, text: str = "text\n") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _skill_tree(root: Path) -> Path:
    """A wikicommit-init Skill with instructions, templates and a planted node_modules/."""
    skill = root / ".claude" / "skills" / "wikicommit-init"
    _write(skill / "SKILL.md")
    _write(skill / "references" / "step.md")
    _write(skill / "CHANGELOG.md")
    _write(skill / "changelog" / "0.1.md")
    _write(skill / "scripts" / "templates" / "guides" / "guide.md")
    _write(skill / PLUGIN / "README.md")
    _write(skill / PLUGIN / "node_modules" / "dep" / "README.md")
    _write(skill / "references" / "node_modules" / "dep" / "README.md")
    return skill


def test_instruction_files_skips_node_modules_and_keeps_its_set(tmp_path):
    skill = _skill_tree(tmp_path)

    found = check_skill_md_lines.instruction_files(skill)

    assert [p.relative_to(skill).as_posix() for p in found] == [
        "SKILL.md",
        "references/step.md",
    ]


def test_check_skill_tree_paths_skips_node_modules(tmp_path, monkeypatch):
    skill = _skill_tree(tmp_path)
    monkeypatch.chdir(tmp_path)

    found = check_skill_tree_paths.collect_files()

    rel = [(tmp_path / p).relative_to(skill).as_posix() for p in found]
    assert rel == [
        "SKILL.md",
        "references/step.md",
        f"{PLUGIN.as_posix()}/README.md",
    ]


def test_install_sh_does_not_distribute_node_modules_or_pycache(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    shutil.copy(REPO / "install.sh", source / "install.sh")
    skill = _skill_tree(source)
    _write(skill / "scripts" / "__pycache__" / "x.cpython-313.pyc")
    _write(skill / "scripts" / "stray.pyc")
    _write(skill / "scripts" / "tool.py")
    target = tmp_path / "target"
    target.mkdir()

    result = subprocess.run(
        ["bash", str(source / "install.sh"), "--yes"],
        cwd=target, capture_output=True, text=True, check=False,
    )

    assert result.returncode == 0, result.stderr
    installed_root = target / ".claude" / "skills" / "wikicommit-init"
    installed = sorted(
        p.relative_to(installed_root).as_posix()
        for p in installed_root.rglob("*") if p.is_file()
    )
    assert installed == sorted([
        "SKILL.md",
        "CHANGELOG.md",
        "changelog/0.1.md",
        "references/step.md",
        "scripts/templates/guides/guide.md",
        f"{PLUGIN.as_posix()}/README.md",
        "scripts/tool.py",
    ])
